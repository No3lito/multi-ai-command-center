# Connects the workspace's linked project folders to the Command Center, read-only.
#
# Reads FILES_FOLDER from .env, then 10-SYSTEM\links.json in that workspace, and writes
# docker-compose.override.yml (next to docker-compose.yml) with one read-only mount per link.
# Docker Compose loads that file automatically. Run it again whenever links.json changes,
# then restart with:  docker compose up -d
# It only writes docker-compose.override.yml. It never touches your folders.
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $repo ".env"
$workspace = $null
if (Test-Path $envFile) {
  foreach ($line in Get-Content $envFile) {
    if ($line -match '^\s*FILES_FOLDER\s*=\s*(.+?)\s*$') { $workspace = $Matches[1].Trim('"', "'") }
  }
}
if (-not $workspace) { throw "FILES_FOLDER is not set in .env" }
$linksFile = Join-Path $workspace "10-SYSTEM\links.json"
if (-not (Test-Path $linksFile)) { throw "No links file at $linksFile" }
$cfg = Get-Content $linksFile -Raw | ConvertFrom-Json
$lines = @(
  "# Generated by infrastructure/workspace-mounts.ps1 on $(Get-Date -Format s). Do not edit by hand.",
  "services:",
  "  app:",
  "    volumes:"
)
$count = 0
foreach ($l in $cfg.links) {
  if (-not (Test-Path $l.target)) { Write-Host "MISSING $($l.target) (skipped)" -ForegroundColor Yellow; continue }
  # Must match mount_key() in backend/command_center/workspace.py
  $key = ($l.project.Trim('/') -replace '/', '__') + "__" + $l.name
  $src = $l.target -replace "'", "''"
  $lines += "      - type: bind"
  $lines += "        source: '$src'"
  $lines += "        target: /sources/$key"
  $lines += "        read_only: true"
  Write-Host "mount   $($l.project)/sources/$($l.name)  (read-only)" -ForegroundColor Green
  $count++
}
if ($count -eq 0) { $lines = @("# No linked folders found.", "services: {}") }
Set-Content -Path (Join-Path $repo "docker-compose.override.yml") -Value $lines -Encoding UTF8
Write-Host "Wrote docker-compose.override.yml with $count read-only mounts. Now run: docker compose up -d"
