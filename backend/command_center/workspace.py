"""The owner's workspace: one folder of projects that every agent can find its way around.

Layout (see the workspace's README and 10-SYSTEM/AGENTS.md):

    00-INBOX/                     anything new; the owner files it with one click
    01-PROJECTS/<family>/<project>/
        PROJECT.md                goal, status, next, rules, where files are
        sources/<name>/           the owner's live folders, linked read-only
        briefs/ decisions/ outputs/ notes/   written by the Command Center
    02-REFERENCE/  09-ARCHIVE/  10-SYSTEM/ (INDEX.md, AGENTS.md, links.json, templates/)

`sources/<name>` folders are Windows junctions on the owner's PC. Docker cannot follow them,
so each linked folder is also mounted read-only at SOURCES_ROOT/<mount_key(project, name)>
(infrastructure/workspace-mounts.ps1 writes that mount list from 10-SYSTEM/links.json).
Every path handed to this module is relative to the workspace root, with forward slashes,
and is checked to stay inside the workspace or inside its linked folder. Writes go only to a
project's briefs/, decisions/, outputs/ or notes/ folders, the project skeleton and the
generated part of INDEX.md, and never overwrite or delete anything.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Literal

from command_center.files import MAX_FILE_BYTES, MAX_LISTED, TEXT_EXTENSIONS, Entry, FileAccessError, Snapshot

PROJECTS_DIR = "01-PROJECTS"
INBOX_DIR = "00-INBOX"
LINKS_FILE = "10-SYSTEM/links.json"
INDEX_FILE = "10-SYSTEM/INDEX.md"
WRITABLE = ("briefs", "decisions", "outputs", "notes")
# Never offered to agents when they pick files (owners can still browse them).
SKIP_FOR_AGENTS = frozenset(
    {"node_modules", ".git", "logs", "raw", "worldmonitor-ref", "__pycache__", ".venv"}
)
INDEX_START = "<!-- projects:start (generated by the Command Center; edit project cards instead) -->"
INDEX_END = "<!-- projects:end -->"

Kind = Literal["briefs", "decisions", "outputs", "notes"]


@dataclass(frozen=True)
class Link:
    project: str  # e.g. 01-PROJECTS/trading/meme-coin-strategy
    name: str  # folder name under sources/
    target: str  # the owner's real folder (Windows path), for reference only

    @property
    def prefix(self) -> str:
        return f"{self.project}/sources/{self.name}"


@dataclass(frozen=True)
class Project:
    path: str  # relative to the workspace root
    family: str
    slug: str
    title: str
    status: str
    goal: str


def mount_key(project: str, name: str) -> str:
    """Folder name of a linked source under SOURCES_ROOT. Must match workspace-mounts.ps1."""
    return project.strip("/").replace("/", "__") + "__" + name


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:60] or "project"


def _clean(relative: str) -> str:
    rel = relative.replace("\\", "/").strip().strip("/")
    parts = [p for p in rel.split("/") if p not in ("", ".")]
    if rel.startswith("/") or ":" in rel or any(p == ".." for p in parts):
        raise FileAccessError("Path must be inside the workspace.")
    return "/".join(parts)


def _inside(base: Path, target: Path) -> bool:
    return target == base or base in target.parents


def _front_matter(text: str) -> dict[str, str]:
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    out: dict[str, str] = {}
    for line in text[3 : end if end > 0 else 0].splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip()
    return out


def _section(text: str, heading: str) -> str:
    m = re.search(rf"^## {heading}\s*\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1).strip() if m else ""


class Workspace:
    def __init__(self, root: Path, sources_root: Path | None = None) -> None:
        self.root = root.resolve()
        self.sources_root = sources_root

    # ------------------------------------------------------------ links and paths

    def links(self) -> list[Link]:
        f = self.root / LINKS_FILE
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return []
        out = []
        for item in data.get("links", []) if isinstance(data, dict) else []:
            try:
                project, name = _clean(str(item["project"])), str(item["name"])
            except (KeyError, FileAccessError):
                continue
            if re.fullmatch(r"[A-Za-z0-9._-]{1,80}", name) and project.startswith(PROJECTS_DIR + "/"):
                out.append(Link(project, name, str(item.get("target", ""))))
        return out

    def _link_for(self, rel: str) -> tuple[Link, str] | None:
        for link in self.links():
            if rel == link.prefix or rel.startswith(link.prefix + "/"):
                return link, rel[len(link.prefix) :].strip("/")
        return None

    def _link_base(self, link: Link) -> Path | None:
        if self.sources_root is not None:
            mounted = self.sources_root / mount_key(link.project, link.name)
            if mounted.is_dir():
                return mounted.resolve()
        local = self.root / link.prefix  # a junction, followed when running natively on Windows
        try:
            return local.resolve() if local.is_dir() else None
        except OSError:
            return None

    def is_source(self, relative: str) -> bool:
        return self._link_for(_clean(relative)) is not None

    def real_path(self, relative: str) -> Path:
        """The real path for a workspace-relative path, or FileAccessError."""
        rel = _clean(relative)
        hit = self._link_for(rel)
        if hit is not None:
            link, rest = hit
            base = self._link_base(link)
            if base is None:
                raise FileAccessError(
                    f"{link.prefix} is linked but not connected to the Command Center; "
                    "run infrastructure/workspace-mounts.ps1 and restart."
                )
            target = (base / rest).resolve() if rest else base
            if not _inside(base, target):
                raise FileAccessError("Path must be inside the linked folder.")
            return target
        target = (self.root / rel).resolve() if rel else self.root
        if not _inside(self.root, target):
            raise FileAccessError("Path must be inside the workspace.")
        return target

    # ------------------------------------------------------------ reading

    def list_dir(self, relative: str = "", *, for_agents: bool = False) -> list[Entry]:
        rel = _clean(relative)
        folder = self.real_path(rel)
        names: dict[str, Entry] = {}
        # Linked sources show even where the junction cannot be followed (inside Docker).
        for link in self.links():
            if link.project + "/sources" == rel:
                names[link.name] = Entry(link.name, link.prefix, "dir", None, False)
        if folder.is_dir():
            for child in sorted(folder.iterdir(), key=lambda p: (not p.is_dir(), p.name.lower())):
                if child.name.startswith(".") or child.name in names:
                    continue
                if for_agents and (child.name in SKIP_FOR_AGENTS or ".bak" in child.name):
                    continue
                path = f"{rel}/{child.name}" if rel else child.name
                try:
                    if child.is_symlink() or not _inside(self.root, child.resolve()):
                        if self._link_for(path) is None:
                            continue  # a link pointing outside, not one of the owner's linked sources
                    if child.is_dir():
                        names[child.name] = Entry(child.name, path, "dir", None, False)
                    elif child.is_file():
                        size = child.stat().st_size
                        ok = child.suffix.lower() in TEXT_EXTENSIONS and size <= MAX_FILE_BYTES
                        names[child.name] = Entry(child.name, path, "file", size, ok)
                except OSError:
                    continue
                if len(names) >= MAX_LISTED:
                    break
        elif not names:
            raise FileAccessError("Not a folder.")
        return sorted(names.values(), key=lambda e: (e.type != "dir", e.name.lower()))

    def read_snapshot(self, relative: str) -> Snapshot:
        rel = _clean(relative)
        target = self.real_path(rel)
        if not target.is_file():
            raise FileAccessError(f"{rel}: not a file.")
        if target.name.startswith("."):
            raise FileAccessError(f"{rel}: hidden files cannot be read.")
        if target.suffix.lower() not in TEXT_EXTENSIONS:
            raise FileAccessError(f"{rel}: only text files can be read.")
        if target.stat().st_size > MAX_FILE_BYTES:
            raise FileAccessError(f"{rel}: larger than 5 MB.")
        raw = target.read_bytes()
        if b"\x00" in raw[:4096]:
            raise FileAccessError(f"{rel}: looks like a binary file.")
        content = raw.decode("utf-8", errors="replace")
        return Snapshot(path=rel, content=content, chars=len(content), sha256=hashlib.sha256(raw).hexdigest())

    def tree(self, relative: str, *, limit: int = 400, depth: int = 4) -> list[Entry]:
        """Readable text files under a folder (including its linked sources), for agents to pick from."""
        out: list[Entry] = []

        def walk(rel: str, level: int) -> None:
            if len(out) >= limit or level > depth:
                return
            try:
                entries = self.list_dir(rel, for_agents=True)
            except (FileAccessError, OSError):
                return
            for e in entries:
                if len(out) >= limit:
                    return
                if e.type == "dir":
                    walk(e.path, level + 1)
                elif e.readable:
                    out.append(e)

        walk(_clean(relative), 0)
        return out

    # ------------------------------------------------------------ projects

    def projects(self) -> list[Project]:
        base = self.root / PROJECTS_DIR
        out: list[Project] = []
        if not base.is_dir():
            return out
        for card in sorted(base.glob("*/*/PROJECT.md")):
            try:
                text = card.read_text(encoding="utf-8")
            except OSError:
                continue
            meta = _front_matter(text)
            headings = (ln[2:].strip() for ln in text.splitlines() if ln.startswith("# "))
            title = next(headings, card.parent.name)
            out.append(
                Project(
                    path=card.parent.relative_to(self.root).as_posix(),
                    family=card.parent.parent.name,
                    slug=card.parent.name,
                    title=title,
                    status=meta.get("status", "active"),
                    goal=_section(text, "Goal")[:500],
                )
            )
        return out

    def project(self, path: str) -> Project | None:
        rel = _clean(path)
        return next((p for p in self.projects() if p.path == rel), None)

    def families(self) -> list[str]:
        base = self.root / PROJECTS_DIR
        if not base.is_dir():
            return []
        return sorted(p.name for p in base.iterdir() if p.is_dir() and not p.name.startswith("."))

    def create_project(self, family: str, name: str, goal: str = "") -> Project:
        fam = slugify(family)
        slug = slugify(name)
        rel = f"{PROJECTS_DIR}/{fam}/{slug}"
        folder = self.root / rel
        if folder.exists():
            existing = self.project(rel)
            if existing is not None:
                return existing
            raise FileAccessError(f"{rel} already exists but has no PROJECT.md.")
        for sub in ("sources", *WRITABLE):
            (folder / sub).mkdir(parents=True, exist_ok=True)
        today = date.today().isoformat()
        family_page = self.root / PROJECTS_DIR / fam / f"{fam.upper()}.md"
        if not family_page.exists():
            family_page.write_text(
                f"---\ntype: family\nupdated: {today}\n---\n# {family.strip() or fam} family\n\n"
                "Projects in this family share rules and lessons. Add shared rules here.\n",
                encoding="utf-8",
            )
        (folder / "PROJECT.md").write_text(
            f"""---
type: project
family: {fam}
status: active
updated: {today}
tags: [project, {fam}]
---
# {name.strip()}

## Goal
{goal.strip() or "Write the goal in one or two sentences."}

## Status
• Created from the Command Center on {today}.

## Next
The first run in this project's room.

## Rules for this project
• See the workspace rules in [[owner-rules]].

## Where the files are
| In this folder | Linked to (read-only) | What it holds |
|---|---|---|
| `briefs/` | | Decision briefs from Command Center runs, saved automatically |
| `decisions/` | | What Noel approved, declined or asked about, and why |
| `outputs/` | | Finished work produced by the agents |
| `notes/` | | Files filed from the inbox |

Family: [[{fam.upper()}]] · Map: [[INDEX]]
""",
            encoding="utf-8",
        )
        self.refresh_index()
        project = self.project(rel)
        assert project is not None
        return project

    def refresh_index(self) -> None:
        """Rewrite only the generated project table in INDEX.md; the rest of the file is the owner's."""
        index = self.root / INDEX_FILE
        rows = "\n".join(
            f"| {p.family} | [[{p.path}/PROJECT\\|{p.title}]] | {p.status} | "
            + (", ".join(link.name for link in self.links() if link.project == p.path) or "")
            + " |"
            for p in self.projects()
        )
        header = "| Family | Project | Status | Linked sources |\n|---|---|---|---|"
        table = f"{INDEX_START}\n{header}\n{rows}\n{INDEX_END}"
        text = index.read_text(encoding="utf-8") if index.exists() else "# Map of every project\n"
        if INDEX_START in text and INDEX_END in text:
            start = text.index(INDEX_START)
            end = text.index(INDEX_END) + len(INDEX_END)
            text = text[:start] + table + text[end:]
        else:
            heading = "## All projects (kept up to date by the Command Center)"
            text = f"{text.rstrip()}\n\n{heading}\n\n{table}\n"
        index.parent.mkdir(parents=True, exist_ok=True)
        index.write_text(text, encoding="utf-8")

    # ------------------------------------------------------------ writing

    def write_note(self, project: str, kind: Kind, title: str, body: str, *, when: date | None = None) -> str:
        """Save a new markdown file in a project folder (briefs, decisions, outputs, notes)."""
        if kind not in WRITABLE:
            raise FileAccessError("Agents may only write to briefs, decisions, outputs or notes.")
        proj = self.project(project)
        if proj is None:
            raise FileAccessError(f"{project}: not a project in the workspace.")
        folder = self.root / proj.path / kind
        folder.mkdir(parents=True, exist_ok=True)
        day = (when or date.today()).isoformat()
        stem = f"{day}-{kind.rstrip('s')}-{slugify(title)[:50]}"
        target = folder / f"{stem}.md"
        n = 2
        while target.exists():
            target = folder / f"{stem}-{n}.md"
            n += 1
        target.write_text(body if body.endswith("\n") else body + "\n", encoding="utf-8")
        return target.relative_to(self.root).as_posix()

    # ------------------------------------------------------------ inbox

    def inbox(self) -> list[Entry]:
        try:
            return [e for e in self.list_dir(INBOX_DIR) if e.type == "file" and e.name.lower() != "readme.md"]
        except FileAccessError:
            return []

    def file_from_inbox(self, name: str, project: str) -> str:
        """Move one inbox file into a project's notes/ folder (the owner's click is the approval)."""
        if "/" in name or "\\" in name or name.startswith(".") or name.lower() == "readme.md":
            raise FileAccessError("Pick a file from the inbox.")
        src = self.real_path(f"{INBOX_DIR}/{name}")
        if not src.is_file():
            raise FileAccessError(f"{name} is no longer in the inbox.")
        proj = self.project(project)
        if proj is None:
            raise FileAccessError(f"{project}: not a project in the workspace.")
        folder = self.root / proj.path / "notes"
        folder.mkdir(parents=True, exist_ok=True)
        target = folder / name
        n = 2
        while target.exists():
            target = folder / f"{src.stem}-{n}{src.suffix}"
            n += 1
        src.rename(target)
        return target.relative_to(self.root).as_posix()


def open_workspace(root: Path | None, sources_root: Path | None) -> Workspace | None:
    return Workspace(root, sources_root) if root is not None and root.is_dir() else None


def is_project_workspace(ws: Workspace | None) -> bool:
    return ws is not None and (ws.root / PROJECTS_DIR).is_dir()
